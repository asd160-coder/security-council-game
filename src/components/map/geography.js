/* A frame as a lon/lat box, for deciding what can possibly be on screen. */
const frameBox = (frame) => [frame.lon0, frame.lat0, frame.lon1, frame.lat1];

const overlaps = (b, box) =>
  !(b[2] < box[0] || b[0] > box[2] || b[3] < box[1] || b[1] > box[3]);

/* Project one ring of flat [lon, lat, lon, lat, ...] into an SVG path.

   Written as a loop over a flat array rather than a map over pairs because
   this runs across roughly five thousand points every time the frame changes,
   and the pair form allocated an array per point to do it. */
const ringToPath = (coords, frame) => {
  let d = '';
  for (let i = 0; i < coords.length; i += 2) {
    const x = ((coords[i] - frame.lon0) / (frame.lon1 - frame.lon0)) * frame.width;
    const y = ((frame.lat1 - coords[i + 1]) / (frame.lat1 - frame.lat0)) * frame.height;
    d += `${i ? 'L' : 'M'}${x.toFixed(1)} ${y.toFixed(1)}`;
  }
  return `${d}Z`;
};

/* What to draw for a given frame.

   Rings whose bounding box cannot intersect the frame are skipped rather than
   projected and clipped by the viewport — at hemispheric scale that is most of
   the Arctic archipelago, and in the Caribbean frame it is everything except a
   handful of islands and the Gulf coast. */
export const landFor = (frame) => {
  const box = frameBox(frame);
  const out = [];
  for (let i = 0; i < COASTLINES.length; i += 1) {
    const ring = COASTLINES[i];
    if (!overlaps(ring.b, box)) continue;
    out.push({ key: ring.id ?? `c${i}`, id: ring.id, d: ringToPath(ring.c, frame) });
  }
  return out;
};

export const lakesFor = (frame) => {
  const box = frameBox(frame);
  const out = [];
  for (let i = 0; i < LAKES.length; i += 1) {
    const lake = LAKES[i];
    if (!overlaps(lake.b, box)) continue;
    out.push({ key: `l${i}`, d: ringToPath(lake.c, frame) });
  }
  return out;
};

export const ringPath = (points) =>
  `M ${points.map((p) => `${p.x.toFixed(1)} ${p.y.toFixed(1)}`).join(' L ')} Z`;
