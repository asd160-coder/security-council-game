/* Geography for the situation map.

   The outlines are real. They come from Natural Earth (public domain), clipped
   to the frames this map can actually show and generalised per region — see
   coastlines.js, which is generated by .design/build-coastlines.py.

   They used to be hand-drawn polygons, seventeen points for Cuba and thirty
   for the whole of Eurasia, on the reasoning that the map's job was to show
   the four poles of the crisis rather than to be an atlas. That was true and
   still produced a Cuba nobody could identify as Cuba, which undercut the one
   thing the map exists to make concrete. A shape a student cannot recognise
   cannot carry a fact about distance.

   The range rings are accurate for the same reason: they are computed by
   walking a true great-circle bearing around the launch point, so their shape
   reflects the real projected footprint rather than a drawn ellipse. */

import { COASTLINES, LAKES } from './coastlines.js';

/* Equirectangular projection. Simple, and honest about being a projection. */
export const project = (lon, lat, frame) => ({
  x: ((lon - frame.lon0) / (frame.lon1 - frame.lon0)) * frame.width,
  y: ((frame.lat1 - lat) / (frame.lat1 - frame.lat0)) * frame.height,
});

/* Frame dimensions are DERIVED, not chosen.

   All three frames used to be 1000x520 whatever ground they covered, which
   made the Caribbean frame stretch everything horizontally by a factor of
   1.8: Cuba was drawn very nearly twice as wide as it is, and the range rings
   — the one part of this map whose numbers are exact — were displayed as wide
   ellipses when a great-circle radius near its own centre should read as
   close to a circle.

   So each height is computed from its span such that a degree of longitude
   and a degree of latitude cover the same distance on screen at the frame's
   mid-latitude. That is the equidistant cylindrical projection with a
   standard parallel through the middle of what you are looking at, and it is
   the reason the shapes are now the shapes. The SVG is `width: 100%; height:
   auto`, so the panels follow. */
